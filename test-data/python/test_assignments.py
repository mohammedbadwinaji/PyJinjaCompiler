# 1. Basic Literal Assignments
string_single = 'Hello'
string_double = "World"
int_positive = 42
int_zero = 0
float_value = 3.14159
bool_true = True
bool_false = False
none_value = None

# 2. Expression Assignments
# Arithmetic expression assignments
total = 10 + 20
difference = total - 5
product = int_positive * float_value
ratio = int_positive / 2
remainder = int_positive % 3

# Logical and Comparison assignments
is_male = 5 == 5
is_valid = (total > 10) and bool_true
is_invalid = not is_valid
complex_check = (10 <= 20) or (5 != 5)

# 3. Chained Assignments
a = b = c = 0
x = y = z = "shared_state"
first = second = third = 10 + 5 * 2

# 4. Mixed assignments
dynamic_val = a
dynamic_result = a + b * c